"""Manifests for captured tensor files: what was captured, from which model revision, with sha256.

The large .npz captures live under data/ (gitignored); the manifest.json next to them is committed so
anyone can verify they regenerated byte-identical stimulus.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

MANIFEST = "manifest.json"


def sha256_file(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def write_manifest(root: Path, meta: dict, files: list[Path]) -> Path:
    """Write root/manifest.json listing ``files`` (relative to root) with size + sha256."""
    root = Path(root)
    entries = []
    for f in sorted(files):
        f = Path(f)
        entries.append(
            {"path": str(f.relative_to(root)), "bytes": f.stat().st_size, "sha256": sha256_file(f)}
        )
    doc = {"meta": meta, "files": entries, "total_bytes": sum(e["bytes"] for e in entries)}
    out = root / MANIFEST
    out.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")
    return out


def verify_manifest(root: Path) -> list[str]:
    """Return a list of problems (empty = all files present and hashes match)."""
    root = Path(root)
    doc = json.loads((root / MANIFEST).read_text())
    problems = []
    for e in doc["files"]:
        p = root / e["path"]
        if not p.exists():
            problems.append(f"missing: {e['path']}")
        elif sha256_file(p) != e["sha256"]:
            problems.append(f"sha256 mismatch: {e['path']}")
    return problems
