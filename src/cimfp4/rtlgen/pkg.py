"""Numerics spec -> generated SystemVerilog package (rtl/include/cim_pkg.sv) and spec table.

Single source of truth for every interface width of the v2 macro (R03 §8).
Widths are *derived* from the number formats by enumeration (cimfp4.formats), never typed by hand,
so the RTL, the golden models and docs/spec/numerics.md cannot drift apart.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np

from ..formats.codecs import E4M3_VALUES, UE8M0_EMAX, UE8M0_EMIN, e4m3_significand
from ..formats.tables import PRODUCT_MAG_X4, block_sum_bits


def signed_bits(lo: int, hi: int) -> int:
    """Minimum two's-complement width holding every integer in [lo, hi]."""
    n = 1
    while not (-(1 << (n - 1)) <= lo and hi <= (1 << (n - 1)) - 1):
        n += 1
    return n


def unsigned_bits(hi: int) -> int:
    return max(1, int(hi).bit_length())


@dataclass(frozen=True)
class CimParams:
    rows: int = 32  # K-dimension per column = one MX block
    cols: int = 32  # weight columns (output channels) per macro
    weight_sets: int = 16  # M weight sets per compute unit
    window: int = 40  # accumulator window W (final value from WP-16)
    write_port_bits: int = 256  # weight write port (>=256 b for ping-pong at R>=16)
    derived: dict = field(default_factory=dict, compare=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "derived", derive(self))


def derive(p: CimParams) -> dict:
    max_mag = int(PRODUCT_MAG_X4.max())  # 144
    mx_u, mx_s = block_sum_bits(p.rows)  # 13 / 14
    nv_u, nv_s = block_sum_bits(p.rows // 2)  # 12 / 13
    # NVFP4 scale significands u ∈ [0, 15] (E4M3 1.mmm·8 or 0.mmm·8), exponents k
    finite = np.isfinite(E4M3_VALUES) & (E4M3_VALUES >= 0)
    u, k = e4m3_significand(np.nonzero(finite)[0].astype(np.uint8))
    nv_scale_prod_max = int(u.max()) ** 2  # 225
    nv_term_max = (p.rows // 2) * max_mag * nv_scale_prod_max  # 518400
    nv_exp_lo, nv_exp_hi = 2 * int(k.min()) - 2, 2 * int(k.max()) - 2
    mx_exp_lo, mx_exp_hi = 2 * UE8M0_EMIN - 2, 2 * UE8M0_EMAX - 2
    # alignment shift d saturates at W-1: d >= BASE + int_bits already floors a term to 0/-1, and
    # BASE + int_bits = W - 1 - guard <= W - 1 for every guard >= 0
    shift_max = p.window - 1
    d = {
        "ELEM_BITS": 4,
        "ROW_MAG_BITS": unsigned_bits(12),  # |x|·2 ∈ [0, 12]       -> 4
        "ROW_MAG3_BITS": unsigned_bits(36),  # 3·|x|·2 ∈ [0, 36]     -> 6
        "ROW_BCAST_WIRES": unsigned_bits(12) + unsigned_bits(36) + 1,  # X', 3X', sign -> 11
        "PROD_MAG_BITS": unsigned_bits(max_mag),  # 8
        "PROD_TC_BITS": signed_bits(-max_mag, max_mag),  # 9
        "MX_SUM_U_BITS": mx_u,
        "MX_SUM_S_BITS": mx_s,  # 13 / 14
        "NV_SUM_U_BITS": nv_u,
        "NV_SUM_S_BITS": nv_s,  # 12 / 13
        "UE8M0_BITS": 8,
        "MX_EXP_SUM_BITS": signed_bits(mx_exp_lo, mx_exp_hi),  # 9 (incl. the -2 constant)
        "E4M3_BITS": 8,
        "NV_SCALE_SIG_BITS": unsigned_bits(int(u.max())),  # 4
        "NV_SCALE_PROD_BITS": unsigned_bits(nv_scale_prod_max),  # 8
        "NV_TERM_BITS": signed_bits(-nv_term_max, nv_term_max),  # 20
        "NV_EXP_SUM_BITS": signed_bits(nv_exp_lo, nv_exp_hi),
        "WINDOW_BITS": p.window,
        "SHIFT_BITS": unsigned_bits(shift_max),
        "SET_IDX_BITS": unsigned_bits(p.weight_sets - 1),
        "CSA_OUT_BITS_MX": mx_s,  # each of the 2 carry-save vectors
        "PIPE_FLOPS_PER_COL_MX": 2 * mx_s,  # 28
        "WRITE_PORT_BITS": p.write_port_bits,
        "WEIGHTS_PER_WRITE": p.write_port_bits // 4,
    }
    d["_ranges"] = {
        "mx_exp_sum": (mx_exp_lo, mx_exp_hi),
        "nv_exp_sum": (nv_exp_lo, nv_exp_hi),
        "nv_term": (-nv_term_max, nv_term_max),
        "shift_max": shift_max,
    }
    return d


def emit_sv(p: CimParams) -> str:
    d = p.derived
    lines = [
        "// AUTO-GENERATED by cimfp4.rtlgen.pkg - DO NOT EDIT. Regenerate: make rtl-gen",
        "// Source of truth: src/cimfp4/rtlgen/pkg.py (widths derived from the number formats).",
        "package cim_pkg;",
        f"  localparam int ROWS = {p.rows};",
        f"  localparam int COLS = {p.cols};",
        f"  localparam int WEIGHT_SETS = {p.weight_sets};",
    ]
    for name, val in d.items():
        if not name.startswith("_"):
            lines.append(f"  localparam int {name} = {val};")
    lines += [
        f"  localparam int MX_EXP_SUM_MIN = {d['_ranges']['mx_exp_sum'][0]};",
        f"  localparam int MX_EXP_SUM_MAX = {d['_ranges']['mx_exp_sum'][1]};",
        "  localparam logic [7:0] UE8M0_NAN = 8'hFF;",
        "  localparam int PROD_EXP_OFFSET = -2;  // products are in units of 2^-2",
        "endpackage : cim_pkg",
        "",
    ]
    return "\n".join(lines)


def emit_defines(p: CimParams) -> str:
    """Verilog-2005 `define header (Yosys-compatible; the RTL uses these, cim_pkg.sv mirrors them)."""
    d = p.derived
    lines = [
        "// AUTO-GENERATED by cimfp4.rtlgen.pkg - DO NOT EDIT. Regenerate: make rtl-gen",
        "`ifndef CIM_DEFS_VH",
        "`define CIM_DEFS_VH",
        f"`define CIM_ROWS {p.rows}",
        f"`define CIM_COLS {p.cols}",
        f"`define CIM_WEIGHT_SETS {p.weight_sets}",
    ]
    lines += [f"`define CIM_{k} {v}" for k, v in d.items() if not k.startswith("_")]
    lines += [
        "`define CIM_LEAF_FP4 0",
        "`define CIM_LEAF_GENERIC 1",
        "`define CIM_STORE_SRAM 0",
        "`define CIM_STORE_LATCH 1",
        "`endif",
        "",
    ]
    return "\n".join(lines)


def spec_table(p: CimParams) -> str:
    rows = ["| Parameter | Value |", "|---|---|"]
    rows += [f"| `{k}` | {v} |" for k, v in asdict(p).items() if k != "derived"]
    rows += [f"| `{k}` | {v} |" for k, v in p.derived.items() if not k.startswith("_")]
    rows += [f"| range `{k}` | {v} |" for k, v in p.derived["_ranges"].items()]
    return "\n".join(rows) + "\n"


def write_all(p: CimParams | None = None, root: Path | None = None) -> list[Path]:
    from ..utils.provenance import REPO_ROOT

    p = p or CimParams()
    root = root or REPO_ROOT
    sv = root / "rtl" / "include" / "cim_pkg.sv"
    sv.parent.mkdir(parents=True, exist_ok=True)
    sv.write_text(emit_sv(p))
    (root / "rtl" / "include" / "cim_defs.vh").write_text(emit_defines(p))
    tbl = root / "docs" / "spec" / "numerics_table.md"
    tbl.parent.mkdir(parents=True, exist_ok=True)
    tbl.write_text("<!-- AUTO-GENERATED by cimfp4.rtlgen.pkg — do not edit -->\n" + spec_table(p))
    return [sv, root / "rtl" / "include" / "cim_defs.vh", tbl]
