"""Compositional formal obligations for the generated column trees (T1.4).

The monolithic 32-input tree vs an arithmetic sum is not proven directly (it times out); instead
the generated netlist is cut into the slices recorded by ``build_column_tree`` (``Netlist.slices``):

    h0, h1  : 16-row Dadda half trees, reduced at the full width w to a carry-save pair (s, c)
    merge   : 4:2 Dadda merge of the four full-width half rows to (m_s, m_c)

and three kinds of obligation are emitted as Yosys scripts (``sat`` / MiniSAT, no SBY/EQY needed):

    S_<slice> : the slice, taken cell-for-cell from the netlist, meets its arithmetic contract
                s + c ≡ Σ_r val(r)   (mod 2^w)   for every input (no assumptions)
                m_s + m_c ≡ a + b + c + d   (mod 2^w)
                val(r) = signed(in_r) + s_r (oc), signed(in_r) (tc), in_r (unsigned)
    LINK      : the committed ``rtl/gen/<tree>.sv`` (the monolith every design instantiates) is
                equivalent to the composition of the slice modules (structural miter; identical cells)
    REGEN     : ``rtl/gen/<tree>.sv`` is byte-identical to ``emit_sv(build_column_tree(...))``
                (checked in Python by the driver)

Composition (by hand, modular arithmetic): m ≡ (h0_s + h0_c) + (h1_s + h1_c) ≡ Σ_r val(r) (mod 2^w),
and the half outputs are the low w_half bits of the full-width half pairs, so h_k ≡ Σ_half val (mod
2^w_half). With the leaf miter (|p| ≤ 144 per row) the sums fit in w (resp. w_half) bits signed, so
the modular statements are exact.
"""

from __future__ import annotations

from .tree import Netlist


def _io_groups(nl: Netlist, name: str) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """Input and output groups (name -> nets LSB first) of one slice."""
    half = nl.n_inputs // 2
    if name in ("h0", "h1"):
        rows = range(0, half) if name == "h0" else range(half, nl.n_inputs)
        ins = {"x": [f"in_{r}_{b}" for r in rows for b in range(nl.w_in)]}
        if nl.scheme == "oc":
            ins["sb"] = [f"s_{r}" for r in rows]
        return ins, {"os": nl.rows[f"{name}_s_full"], "oc": nl.rows[f"{name}_c_full"]}
    if name == "merge":
        ins = {
            k: nl.rows[r]
            for k, r in zip("abcd", ("h0_s_full", "h0_c_full", "h1_s_full", "h1_c_full"), strict=True)
        }
        return ins, {"os": nl.outputs["m_s"], "oc": nl.outputs["m_c"]}
    raise ValueError(name)


def emit_slice_sv(nl: Netlist, name: str) -> str:
    """One slice as a module with ports = its input/output groups; cells copied from the netlist."""
    a, b = nl.slices[name]
    cells = nl.cells[a:b]
    ins, outs = _io_groups(nl, name)
    port_of: dict[str, str] = {}
    for g, nets in ins.items():
        for i, n in enumerate(nets):
            if n not in ("0", "1"):
                assert n not in port_of, f"net {n} appears twice in the slice inputs"
                port_of[n] = f"{g}[{i}]"
    produced = {c.sum for c in cells} | {c.carry for c in cells if c.carry}
    for c in cells:  # closure: every consumed net is a constant, a slice input or produced inside
        for n in c.ins:
            assert n in ("0", "1") or n in port_of or n in produced, f"{name}: dangling input {n}"

    def ref(n: str) -> str:
        if n in ("0", "1"):
            return f"1'b{n}"
        if n in port_of:
            return port_of[n]
        assert n in produced, f"{name}: output net {n} not produced"
        return n

    mod = f"{nl.name}_slice_{name}"
    lines = [
        f"// AUTO-GENERATED by cimfp4.rtlgen.tree_slices — slice '{name}' of {nl.name} ({b - a} cells).",
        f"module {mod} (",
    ]
    ports = [f"  input  logic [{len(v) - 1}:0] {g}" for g, v in ins.items()]
    ports += [f"  output logic [{len(v) - 1}:0] {g}" for g, v in outs.items()]
    lines.append(",\n".join(ports))
    lines.append(");")
    for w in sorted(produced, key=lambda s: int(s[1:])):
        lines.append(f"  logic {w};")
    for c in cells:
        x = [ref(n) for n in c.ins]
        if c.kind == "INV":
            lines.append(f"  assign {c.sum} = ~{x[0]};")
        elif c.kind == "HA":
            lines.append(f"  assign {c.sum} = {x[0]} ^ {x[1]};  assign {c.carry} = {x[0]} & {x[1]};")
        elif c.kind == "FA":
            lines.append(
                f"  assign {c.sum} = {x[0]} ^ {x[1]} ^ {x[2]};  "
                f"assign {c.carry} = ({x[0]} & {x[1]}) | ({x[0]} & {x[2]}) | ({x[1]} & {x[2]});"
            )
        else:
            raise ValueError(c.kind)
    for g, nets in outs.items():
        lines.append(f"  assign {g} = {{{', '.join(ref(n) for n in reversed(nets))}}};")
    lines.append(f"endmodule : {mod}\n")
    return "\n".join(lines)


def emit_slice_check_sv(nl: Netlist, name: str) -> str:
    """Wrapper `<slice>_chk` with free inputs and one output ``ok`` = (slice meets its contract)."""
    ins, outs = _io_groups(nl, name)
    w = len(outs["os"])
    mod = f"{nl.name}_slice_{name}"
    free = []
    conn = {}
    for g, nets in ins.items():
        bits = []
        for i, n in enumerate(nets):
            if n in ("0", "1"):
                bits.append(f"1'b{n}")  # constant positions of an internal row are fixed by the netlist
            else:
                free.append(f"{g}_{i}")
                bits.append(f"{g}_{i}")
        conn[g] = "{" + ", ".join(reversed(bits)) + "}"
    lines = [
        f"// AUTO-GENERATED by cimfp4.rtlgen.tree_slices — contract check for slice '{name}'.",
        f"module {mod}_chk (",
        "  input logic " + ", ".join(free) + ",",
        "  output logic ok",
        ");",
    ]
    for g, nets in ins.items():
        lines.append(f"  logic [{len(nets) - 1}:0] {g};  assign {g} = {conn[g]};")
    lines.append(f"  logic [{w - 1}:0] os, oc, got, want;")
    lines.append(f"  {mod} u_dut ({', '.join(f'.{g}({g})' for g in ins)}, .os(os), .oc(oc));")
    lines.append("  assign got = os + oc;")
    if name == "merge":
        lines.append("  assign want = a + b + c + d;")
    else:
        rows = len(ins["x"]) // nl.w_in
        terms = []
        for r in range(rows):
            x = f"x[{r * nl.w_in + nl.w_in - 1}:{r * nl.w_in}]"
            if nl.scheme == "unsigned":
                terms.append(f"{w}'({x})")
            else:  # two's complement value of the w_in-bit row, sign-extended to w
                ext = w - nl.w_in
                terms.append(f"{{{{{ext}{{x[{r * nl.w_in + nl.w_in - 1}]}}}}, {x}}}")
            if nl.scheme == "oc":
                terms.append(f"{w}'(sb[{r}])")
        lines.append("  assign want = " + "\n    + ".join(terms) + ";")
    lines.append("  assign ok = (got == want);")
    lines.append(f"endmodule : {mod}_chk\n")
    return "\n".join(lines)


def emit_composed_sv(nl: Netlist) -> str:
    """Composition of the slices with the same ports as the monolith (module ``<tree>_composed``)."""
    w = len(nl.outputs["m_s"])
    wh = len(nl.outputs["h0_s"])
    half = nl.n_inputs // 2
    bpr = nl.w_in
    oc = nl.scheme == "oc"
    lines = [
        f"// AUTO-GENERATED by cimfp4.rtlgen.tree_slices — slice composition of {nl.name}.",
        f"module {nl.name}_composed (",
        f"  input  logic [{nl.n_inputs * bpr - 1}:0] in_bits,",
    ]
    if oc:
        lines.append(f"  input  logic [{nl.n_inputs - 1}:0] s_bits,")
    lines += [
        f"  output logic [{wh - 1}:0] h0_s, h0_c, h1_s, h1_c,",
        f"  output logic [{w - 1}:0] m_s, m_c",
        ");",
        f"  logic [{w - 1}:0] a, b, c, d;",
    ]
    for h, (lo, hi) in enumerate(((0, half), (half, nl.n_inputs))):
        sb = f", .sb(s_bits[{hi - 1}:{lo}])" if oc else ""
        so, co = ("a", "b") if h == 0 else ("c", "d")
        lines.append(
            f"  {nl.name}_slice_h{h} u_h{h} (.x(in_bits[{hi * bpr - 1}:{lo * bpr}]){sb}, "
            f".os({so}), .oc({co}));"
        )
    lines.append(f"  {nl.name}_slice_merge u_m (.a(a), .b(b), .c(c), .d(d), .os(m_s), .oc(m_c));")
    lines.append(f"  assign h0_s = a[{wh - 1}:0];  assign h0_c = b[{wh - 1}:0];")
    lines.append(f"  assign h1_s = c[{wh - 1}:0];  assign h1_c = d[{wh - 1}:0];")
    lines.append(f"endmodule : {nl.name}_composed\n")
    return "\n".join(lines)


def slice_check_ys(nl: Netlist, name: str, files: list[str]) -> str:
    """Yosys script proving `ok == 1` for all inputs (exit code != 0 if not proven)."""
    return "\n".join(
        [
            f"# T1.4 obligation S_{name} for {nl.name}",
            "read_verilog -sv " + " ".join(files),
            f"hierarchy -top {nl.name}_slice_{name}_chk",
            "proc; flatten; opt -fast",
            "sat -verify -prove ok 1 -show-inputs",
            "",
        ]
    )


def link_ys(nl: Netlist, rtl: str, files: list[str]) -> str:
    """Yosys script: committed monolith == composition of slices (structural miter)."""
    return "\n".join(
        [
            f"# T1.4 obligation LINK for {nl.name}: {rtl} == composition of the slices",
            f"read_verilog -sv {rtl} " + " ".join(files),
            "hierarchy -check; proc; opt_clean",
            f"rename {nl.name} gold_mono",
            f"miter -equiv -flatten -make_outputs gold_mono {nl.name}_composed miter",
            "hierarchy -top miter",
            "flatten; opt -full",
            "sat -verify -prove trigger 0",
            "",
        ]
    )
