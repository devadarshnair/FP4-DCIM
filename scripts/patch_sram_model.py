#!/usr/bin/env python3
"""Make the OpenRAM behavioural SRAM model Icarus-compatible for gate-level simulation (WP-27).

Icarus rejects the model's debug `$display(... mem[addr_reg] ...)` statements (non-constant scope
index). This script copies the PDK model to build/models/ removing *only* `$display` statements;
read/write behaviour is untouched (the RTL regressions already use the unmodified model in Verilator).

Usage: python scripts/patch_sram_model.py [SRC] [DST]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path.home() / ".ciel/sky130A/libs.ref/sky130_sram_macros/verilog/sky130_sram_1kbyte_1rw1r_32x256_8.v"
DST = ROOT / "build/models/sky130_sram_1kbyte_1rw1r_32x256_8_gls.v"


def patch(text: str) -> tuple[str, int]:
    # `$display(...);` possibly spanning lines; replace each with an empty statement
    pat = re.compile(r"\$display\s*\((?:[^;])*?\)\s*;", re.S)
    out, n = pat.subn(";", text)
    return out, n


def main(argv=None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    src = Path(argv[0]) if argv else SRC
    dst = Path(argv[1]) if len(argv) > 1 else DST
    text, n = patch(src.read_text())
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(
        f"// GENERATED by scripts/patch_sram_model.py from {src} — {n} $display statements removed\n" + text
    )
    print(f"wrote {dst} ({n} $display removed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
