#!/usr/bin/env python3
"""sky130 tech LEF -> flows/pdk/wire_model.yaml: wire capacitance per µm per routing layer (WP-39).

C/µm (pF) = CPERSQDIST · WIDTH + 2 · EDGECAPACITANCE (LEF units: pF/µm² and pF/µm), for the default
(minimum) width. Every value carries its source file and line number. Used for the X'/3X' broadcast,
the v2 column wires and the baseline (c) weight bus in the power flow (WP-28).

Usage: python scripts/wire_cap_from_lef.py [--tlef PATH] [--out flows/pdk/wire_model.yaml]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TLEF = Path.home() / ".ciel/sky130A/libs.ref/sky130_fd_sc_hd/techlef/sky130_fd_sc_hd__nom.tlef"


def parse(tlef: Path, layers=("met1", "met2", "met3", "met4", "met5")) -> dict:
    lines = tlef.read_text().splitlines()
    out = {}
    cur = None
    for i, line in enumerate(lines, 1):
        m = re.match(r"\s*LAYER\s+(\S+)\s*$", line)
        if m:
            cur = m.group(1) if m.group(1) in layers else None
            if cur:
                out[cur] = {"source": {"file": str(tlef), "layer_line": i}}
            continue
        if cur is None:
            continue
        if re.match(rf"\s*END\s+{cur}\b", line):
            cur = None
            continue
        for key, rx in (
            ("width_um", r"^\s*WIDTH\s+([\d.]+)\s*;"),
            ("pitch_um", r"^\s*PITCH\s+([\d.]+)\s*;"),
            ("edge_cap_pf_per_um", r"EDGECAPACITANCE\s+([\d.Ee+-]+)\s*;"),
            ("area_cap_pf_per_um2", r"CAPACITANCE\s+CPERSQDIST\s+([\d.Ee+-]+)\s*;"),
            ("r_per_sq_ohm", r"RESISTANCE\s+RPERSQ\s+([\d.Ee+-]+)\s*;"),
        ):
            mm = re.search(rx, line)
            if mm and key not in out[cur]:
                out[cur][key] = float(mm.group(1))
                out[cur]["source"][key + "_line"] = i
    for rec in out.values():
        rec["cap_ff_per_um"] = round(
            1e3 * (rec["area_cap_pf_per_um2"] * rec["width_um"] + 2 * rec["edge_cap_pf_per_um"]), 5
        )
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tlef", type=Path, default=DEFAULT_TLEF)
    ap.add_argument("--out", type=Path, default=ROOT / "flows/pdk/wire_model.yaml")
    a = ap.parse_args(argv)
    model = {
        "pdk": "sky130A",
        "formula": "C/um = CPERSQDIST*WIDTH + 2*EDGECAPACITANCE (min width)",
        "layers": parse(a.tlef),
    }
    a.out.write_text(
        "# AUTO-GENERATED by scripts/wire_cap_from_lef.py — do not edit\n"
        + yaml.safe_dump(model, sort_keys=False)
    )
    for k, v in model["layers"].items():
        print(f"{k}: {v['cap_ff_per_um']:.4f} fF/um (w={v['width_um']} um)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
