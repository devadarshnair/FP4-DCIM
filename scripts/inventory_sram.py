#!/usr/bin/env python3
"""Inventory the local sky130 OpenRAM macros -> flows/pdk/sram_macros.yaml (WP-63; no hand-typed values).

Per macro: words × bits (from the behavioural Verilog parameters), ports (from the name), LEF size and
area, Liberty area/leakage per corner, and the clock-pin internal power (energy per edge, pJ) per
access condition. NOTE: the shipped OpenRAM Liberty uses one constant internal_power value for all
conditions (read/write/idle) - recorded as-is and flagged `energy_quality: placeholder`.

Usage: python scripts/inventory_sram.py [--pdk ~/.ciel/sky130A] [--out flows/pdk/sram_macros.yaml]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def parse_verilog(v: Path) -> dict:
    t = v.read_text()
    get = lambda name: int(re.search(rf"parameter\s+{name}\s*=\s*(\d+)", t).group(1))  # noqa: E731
    return {
        "data_width": get("DATA_WIDTH"),
        "addr_width": get("ADDR_WIDTH"),
        "num_wmasks": get("NUM_WMASKS"),
        "words": 1 << get("ADDR_WIDTH"),
    }


def parse_lef(lef: Path) -> dict:
    m = re.search(r"SIZE\s+([\d.]+)\s+BY\s+([\d.]+)", lef.read_text())
    w, h = float(m.group(1)), float(m.group(2))
    return {"lef_w_um": w, "lef_h_um": h, "lef_area_um2": round(w * h, 3)}


def parse_lib(lib: Path) -> dict:
    t = lib.read_text()
    units = {
        k: re.search(rf'{k}\s*:\s*"([^"]+)"', t).group(1)
        for k in ("time_unit", "voltage_unit", "leakage_power_unit")
    }
    cap = re.search(r"capacitive_load_unit\s*\(\s*([\d.]+)\s*,\s*(\w+)\s*\)", t)
    out = {
        "units": {**units, "capacitive_load_unit": f"{cap.group(1)}{cap.group(2)}"},
        "area_um2": float(re.search(r"\barea\s*:\s*([\d.eE+-]+)", t).group(1)),
        "leakage_mw": float(re.search(r"^\s*cell_leakage_power\s*:\s*([\d.eE+-]+)", t, re.M).group(1)),
    }
    # internal power on clock pins, per 'when' condition: rise/fall energy (V^2*pF = pJ)
    energies = {}
    for pin in re.finditer(r"pin\s*\(\s*(clk\d)\s*\)\s*\{", t):
        body = t[pin.end() : pin.end() + 6000]
        body = body[: body.find("\n    pin(")] if "\n    pin(" in body else body
        for ip in re.finditer(
            r'internal_power\(\)\{\s*when\s*:\s*"([^"]+)";.*?rise_power\(scalar\)\{\s*values\("([^"]+)"\);'
            r'.*?fall_power\(scalar\)\{\s*values\("([^"]+)"\);',
            body,
            re.S,
        ):
            energies[f"{pin.group(1)}[{ip.group(1)}]"] = {
                "rise_pj": float(ip.group(2)),
                "fall_pj": float(ip.group(3)),
            }
    out["clk_internal_energy"] = energies
    vals = {(e["rise_pj"], e["fall_pj"]) for e in energies.values()}
    out["energy_quality"] = (
        "placeholder (constant for all conditions)" if len(vals) == 1 else "condition-dependent"
    )
    return out


def corner_of(lib: Path) -> str:
    m = re.search(r"_(TT|FF|SS)_(\dp\dV)_(\d+C)\.lib$", lib.name)
    return f"{m.group(1)}_{m.group(2)}_{m.group(3)}" if m else lib.stem


def inventory(pdk: Path) -> dict:
    d = pdk / "libs.ref" / "sky130_sram_macros"
    out = {"pdk": str(pdk.resolve()), "macros": {}}
    for v in sorted((d / "verilog").glob("*.v")):
        name = v.stem
        lef = d / "lef" / f"{name}.lef"
        libs = sorted((d / "lib").glob(f"{name}_*.lib"))
        if not lef.exists() or not libs:
            continue
        rec = {**parse_verilog(v), **parse_lef(lef), "ports": re.search(r"(\d+rw\d*r?)", name).group(1)}
        rec["bits"] = rec["words"] * rec["data_width"]
        rec["kb_per_mm2"] = round(rec["bits"] / 1024 / (rec["lef_area_um2"] * 1e-6), 2)
        rec["corners"] = {corner_of(lib): parse_lib(lib) for lib in libs}
        tt = rec["corners"].get("TT_1p8V_25C") or next(iter(rec["corners"].values()))
        e_edge = max(e["rise_pj"] + e["fall_pj"] for e in tt["clk_internal_energy"].values())
        rec["read_energy_pj_per_word_tt"] = round(e_edge, 4)  # one clock cycle (rise + fall) per access
        rec["read_energy_pj_per_bit_tt"] = round(e_edge / rec["data_width"], 5)
        rec["files"] = {"verilog": str(v), "lef": str(lef), "libs": [str(x) for x in libs]}
        out["macros"][name] = rec
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdk", type=Path, default=Path.home() / ".ciel" / "sky130A")
    ap.add_argument("--out", type=Path, default=ROOT / "flows" / "pdk" / "sram_macros.yaml")
    args = ap.parse_args(argv)
    inv = inventory(args.pdk)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "# AUTO-GENERATED by scripts/inventory_sram.py — do not edit\n" + yaml.safe_dump(inv, sort_keys=False)
    )
    for n, r in inv["macros"].items():
        print(
            f"{n:40s} {r['words']:5d}x{r['data_width']:<3d} {r['bits'] / 1024:5.1f} Kb  "
            f"{r['lef_area_um2'] / 1e6:6.3f} mm2  {r['kb_per_mm2']:6.1f} Kb/mm2  "
            f"{r['read_energy_pj_per_bit_tt']:.3f} pJ/bit/access"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
