"""e00 - analytic, pre-registered gain budget (WP-60). Also generates the G1 pre-registration note.

Run: python experiments/e00_gain_budget/run.py [--paper]
"""

from __future__ import annotations

import argparse
import hashlib

import yaml

from cimfp4.power.gain_budget import alignment_upper_bound, budget, pick
from cimfp4.utils.provenance import REPO_ROOT
from cimfp4.utils.runlog import start_run

CFG = REPO_ROOT / "experiments" / "configs" / "gain_budget.yaml"
PREREG = REPO_ROOT / "docs" / "plan" / "G1_prereg.md"
SCENARIOS = ("pessimistic", "nom", "optimistic")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", action="store_true")
    ap.add_argument("--write-prereg", action="store_true", help="(re)generate G1_prereg.md")
    args = ap.parse_args()
    cfg = yaml.safe_load(CFG.read_text())
    cfg_sha = hashlib.sha256(CFG.read_bytes()).hexdigest()
    with start_run("e00_gain_budget", {"config_sha256": cfg_sha, **cfg}, paper=args.paper) as run:
        budget_rows, lever_rows, ratios = [], [], {}
        for bname, b in cfg["baselines"].items():
            for sc in SCENARIOS:
                ratio, levers, final = budget(b["components"], bname, pick(cfg["params"], sc))
                ratios[(bname, sc)] = ratio
                budget_rows.append(
                    {
                        "baseline": bname,
                        "scenario": sc,
                        "ee_ratio_v2_over_base": ratio,
                        **{f"v2_{k}": v for k, v in final.items()},
                    }
                )
                for i, (lname, lval) in enumerate(levers):
                    lever_rows.append(
                        {"baseline": bname, "scenario": sc, "order": i, "lever": lname, "ratio": lval}
                    )
        run.save_csv("budget.csv", budget_rows)
        run.save_csv("levers.csv", lever_rows)
        align_ub = alignment_upper_bound(cfg["baselines"]["midas_like"]["components"], cfg["params"])
        g = cfg["g1_prereg"]
        g0_pass = (
            ratios[("bitserial_int5", "optimistic")] >= g["g0_budget_vs_int5_optimistic"]
            or ratios[("digital_mac", "optimistic")] >= g["g0_budget_vs_c_optimistic"]
        )
        metrics = {f"ee_{b}_{s}": r for (b, s), r in ratios.items()}
        metrics |= {
            "alignment_lever_upper_bound": align_ub,
            "g0_budget_pass": g0_pass,
            "config_sha256": cfg_sha,
        }
        run.log_metrics(metrics)
        for (b, s), r in ratios.items():
            print(f"{b:15s} {s:12s} EE(v2)/EE(base) = {r:5.2f}")
        print(f"alignment-removal lever upper bound = {align_ub:.3f}x ; G0 budget check pass = {g0_pass}")

        if args.write_prereg:
            lines = [
                "# G1 pre-registration (generated by experiments/e00_gain_budget/run.py — FROZEN once committed)\n",
                f"\nConfig: `experiments/configs/gain_budget.yaml` sha256 `{cfg_sha}`; run `{run.run_id}`.\n",
                "\n## Thresholds (pre-registered)\n",
                f"- **Go:** EE(v2)/EE(bit-serial INT5) ≥ {g['go_ratio_vs_int5']} with bootstrap 95 % lower bound ≥ {g['go_lower_ci']}"
                " (sky130 hd tt_025C_1v80, common clock, identical stimulus, column + storage/wire/clock/leakage, M=16 SRAM, R=256).\n",
                f"- **Conditional:** {g['conditional_low']} ≤ ratio < {g['go_ratio_vs_int5']}. **Fallback:** ratio < {g['conditional_low']}"
                f" or TFLOPS/mm² ratio < 0.4.\n",
                f"- **Area floor:** TFLOPS/mm²(v2)/TFLOPS/mm²(INT5, iso-throughput) ≥ {g['area_floor_tflops_mm2']}.\n",
                f'- "CIM advantage" wording vs digital MAC (c) requires ≥ {g["cim_advantage_vs_c"]}.\n',
                "- Blocking: 0 mismatches for all three columns vs the golden model.\n",
                "\n## Predicted bands (analytic, before RTL)\n\n| Baseline | pessimistic | nominal | optimistic |\n|---|---|---|---|\n",
            ]
            for b in cfg["baselines"]:
                lines.append(
                    f"| {b} | {ratios[(b, 'pessimistic')]:.2f} | {ratios[(b, 'nom')]:.2f} | {ratios[(b, 'optimistic')]:.2f} |\n"
                )
            lines += [
                f"\nAlignment-removal lever alone (vs MIDAS-like): ≤ {align_ub:.3f}×.\n",
                f"\nG0 budget criterion (optimistic vs INT5 ≥ {g['g0_budget_vs_int5_optimistic']} or vs (c) ≥ "
                f"{g['g0_budget_vs_c_optimistic']}): **{'PASS' if g0_pass else 'FAIL'}**.\n",
                "\nA measured G1 ratio outside its band requires a lever-level explanation in g1.json (§5 G1(4)).\n",
            ]
            PREREG.write_text("".join(lines))
            print("wrote", PREREG)


if __name__ == "__main__":
    main()
