"""e20 range - low / nominal / high energy of the sky130 OpenRAM 1 KB macro for the macro comparison
(writes docs/spec/sram_energy.yaml). Results only.

Inputs (latest successful run of each kind, results/index.csv order):
  e20_sram_energy, schematic array   ngspice of the PDK LVS netlist (devices only: no wiring, and the
                                     transistors carry no AD/AS/PD/PS, so diffusion capacitance is absent)
  e20_sram_energy, extracted array   same, with every bitcell replaced by its magic-extracted layout
                                     (device diffusion + in-cell metal = the complete bitline/wordline load)
  e20_sram_cell_caps                 per-cell extracted vs schematic pin capacitance
  e20_cacti                          CACTI 7, 1 KB 1RW+1R, 130 nm itrs-hp, rescaled to 1.8 V [EST]
Corners (energies per event; leakage per macro):
  low      = schematic array: a strict lower bound (wiring and diffusion only add switched capacitance)
  nominal  = extracted array, schematic periphery: array exact to layout; periphery wiring/diffusion
             still missing, so this is itself still low-biased
  high     = 2 x nominal [EST: periphery wiring/diffusion assumed to at most double the macro
             energy], and never below the shipped
             Liberty placeholder per read word (rise+fall = 19.18 pJ) or the CACTI per-word read energy.
Leakage: low = nominal = measured; high = 10 x measured [EST: no diffusion leakage in the schematic
periphery; the shipped Liberty states 9.5 uW]; leakage is < 0.1 % of the idle clock energy either way.

Run: python experiments/e20_sram_energy/range.py
"""

from __future__ import annotations

import csv
import json

import yaml

from cimfp4.utils.provenance import REPO_ROOT

R = REPO_ROOT / "results"
OUT = REPO_ROOT / "docs/spec/sram_energy.yaml"
PLACEHOLDER_PJ_PER_EDGE = 9.589466  # shipped Liberty, every when-condition
KEYS = ["e_idle_cycle_pj", "de_read_dual_pj", "de_read_per_word_dual_pj", "de_set_switch_per_macro_pj",
        "de_read_p0_pj", "de_read_p1_pj", "de_write_flip_half_pj", "de_write_flip_all_pj", "leakage_uw"]


def runs(exp: str) -> list[str]:
    with open(R / "index.csv") as f:
        return [r["path"] for r in csv.DictReader(f) if r["exp"] == exp and r["status"] == "ok"]


def load(path: str) -> tuple[dict, dict]:
    d = R / path
    return json.loads((d / "metrics.json").read_text()), yaml.safe_load((d / "config.yaml").read_text())


def main() -> None:
    sch = ext = None
    for p in runs("e20_sram_energy"):
        m, c = load(p)
        if "read_check_failures" not in m or m["read_check_failures"]:
            continue
        if c.get("cell_ext"):
            ext = (p, m)
        else:
            sch = (p, m)
    if sch is None or ext is None:
        raise SystemExit(f"need a schematic and an extracted e20 run (have {sch and sch[0]}, {ext and ext[0]})")
    caps = runs("e20_sram_cell_caps")
    cacti = runs("e20_cacti")
    cm = load(cacti[-1])[0]["itrs-hp"] if cacti else None
    low = {k: sch[1][k] for k in KEYS}
    nom = {k: ext[1][k] for k in KEYS}
    high = {k: 2 * nom[k] for k in KEYS}
    high["leakage_uw"] = 10 * nom["leakage_uw"]
    floor_word = max(2 * PLACEHOLDER_PJ_PER_EDGE, cm["read_pj_at_1v8"] if cm else 0.0)
    notes = []
    if high["de_read_per_word_dual_pj"] < floor_word:
        f = floor_word / high["de_read_per_word_dual_pj"]
        for k in ("de_read_dual_pj", "de_read_per_word_dual_pj", "de_set_switch_per_macro_pj"):
            high[k] *= f
        notes.append(f"read energies raised x{f:.3f} to the per-word floor {floor_word:.2f} pJ")
    corners = {"low": low, "nominal": nom, "high": high}
    for c in corners.values():
        c["de_dual_read_cycle_pj"] = c["de_read_dual_pj"]
        c["e_idle_clock_cycle_pj"] = c["e_idle_cycle_pj"]
    spec = {
        "macro": "sky130_sram_1kbyte_1rw1r_32x256_8 (OpenRAM, 256 x 32 b, 1RW + 1R), tt, 1.8 V, 27 C, 40 MHz",
        "low_run": sch[0], "nominal_run": ext[0], "cell_caps_run": caps[-1] if caps else None,
        "cacti_run": cacti[-1] if cacti else None, "cacti_itrs_hp": cm,
        "labels": {"low": "measured (SPICE of the PDK schematic netlist, devices only) - lower bound",
                   "nominal": "measured (SPICE, layout-extracted bitcells, schematic periphery)",
                   "high": "[EST] 2 x nominal (periphery wiring/diffusion), floored at Liberty/CACTI per word"},
        "high_notes": notes,
        "liberty_placeholder_pj_per_edge": PLACEHOLDER_PJ_PER_EDGE,
        "units": "pJ per event; de_* = energy above a clocked, deselected (idle) cycle incl. the bitline "
                 "restore in the following cycle; e_idle = one clocked deselected cycle; leakage uW/macro",
        "corners": corners,
    }
    OUT.write_text("# GENERATED by experiments/e20_sram_energy/range.py - do not edit\n"
                   + yaml.safe_dump(spec, sort_keys=False))
    print(yaml.safe_dump(spec, sort_keys=False))


if __name__ == "__main__":
    main()
